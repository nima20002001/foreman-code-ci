import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile, lstat, symlink, link, truncate } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { deflateRawSync } from "node:zlib";
import { describe, it } from "vitest";
import { ArchiveHelperError, ZIP_LIMITS, extractZip, listZip, repackZip } from "./index.js";
import { Budget, crc32 } from "./policy.js";

const fixture = (name: string): Promise<Buffer> => readFile(new URL(`./fixtures/${name}`, import.meta.url));
const archiveError = (code: string) => (error: unknown): boolean => error instanceof ArchiveHelperError && error.code === code;
async function workspace(work: (root: string) => Promise<void>): Promise<void> {
  const root = await mkdtemp(path.join(os.tmpdir(), "fil07-test-"));
  try { await work(root); } finally { await rm(root, { recursive: true, force: true }); }
}
interface TestEntry { name: string; data?: Buffer; compressed?: Buffer; advertisedSize?: number; flags?: number; mode?: number; method?: number; extra?: Buffer }
/** Deliberately permits unsafe metadata for negative tests. Golden ZIP fixtures are independently generated by Python. */
function testZip(rows: readonly TestEntry[]): Buffer {
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  for (const row of rows) {
    const name = Buffer.from(row.name);
    const extra = row.extra ?? Buffer.alloc(0);
    const data = row.data ?? Buffer.from("marker\n");
    const method = row.method ?? 8;
    const compressed = row.compressed ?? (method === 0 ? data : deflateRawSync(data));
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(row.flags ?? 0x0800, 6);
    local.writeUInt16LE(method, 8);
    local.writeUInt32LE(crc32(data), 14);
    local.writeUInt32LE(compressed.length, 18);
    local.writeUInt32LE(row.advertisedSize ?? data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(extra.length, 28);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(0x0314, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(row.flags ?? 0x0800, 8);
    central.writeUInt16LE(method, 10);
    central.writeUInt32LE(crc32(data), 16);
    central.writeUInt32LE(compressed.length, 20);
    central.writeUInt32LE(row.advertisedSize ?? data.length, 24);
    central.writeUInt16LE(name.length, 28);
    central.writeUInt16LE(extra.length, 30);
    central.writeUInt32LE(((row.mode ?? (row.name.endsWith("/") ? 0o40700 : 0o100600)) << 16) >>> 0, 38);
    central.writeUInt32LE(offset, 42);
    locals.push(local, name, extra, compressed);
    centrals.push(central, name, extra);
    offset += local.length + name.length + extra.length + compressed.length;
  }
  const directory = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(rows.length, 8);
  end.writeUInt16LE(rows.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}
function centralOffset(zip: Buffer): number { return zip.readUInt32LE(zip.length - 6); }

describe("FIL-07 ZIP helpers", () => {
  it("checks CRC against an independent standard vector", () => {
    assert.equal(crc32(Buffer.from("123456789")), 0xcbf43926);
    assert.equal(crc32(Buffer.alloc(0)), 0);
  });
  for (const format of ["stored", "deflate"]) {
    it(`lists and selectively extracts an independent ${format} ZIP`, async () => {
      const bytes = await fixture(`${format}.zip`);
      const entries = listZip(bytes);
      assert.deepEqual(entries.map(({ name }) => name), ["docs/README.md", "empty/", "binary.bin"]);
      assert.equal(entries[0]?.uncompressedBytes, 19);
      await workspace(async (root) => {
        const result = await extractZip(bytes, root, ["docs/README.md"]);
        assert.equal(path.dirname(result.workingDirectory), root);
        assert.equal((await readFile(path.join(result.workingDirectory, "docs/README.md"), "utf8")), "# marker\nunchanged\n");
        assert.deepEqual(await readdir(result.workingDirectory), ["docs"]);
        assert.equal((await lstat(result.workingDirectory)).mode & 0o777, 0o700);
        assert.equal((await lstat(path.join(result.workingDirectory, "docs/README.md"))).mode & 0o777, 0o600);
      });
    });
  }
  it("accepts a real deflate data descriptor", async () => {
    await workspace(async (root) => {
      const result = await extractZip(await fixture("descriptor.zip"), root);
      assert.equal(await readFile(path.join(result.workingDirectory, "plain.txt"), "utf8"), "marker\n");
    });
  });
  it("accepts unsigned descriptors and rejects descriptor disagreement", async () => {
    const signed = await fixture("descriptor.zip");
    const cd = centralOffset(signed);
    const descriptor = cd - 16;
    const unsigned = Buffer.concat([signed.subarray(0, descriptor), signed.subarray(descriptor + 4)]);
    unsigned.writeUInt32LE(cd - 4, unsigned.length - 6);
    await workspace(async (root) => {
      const result = await extractZip(unsigned, root);
      assert.equal(await readFile(path.join(result.workingDirectory, "plain.txt"), "utf8"), "marker\n");
    });
    signed[descriptor + 4] = signed[descriptor + 4]! ^ 1;
    assert.throws(() => listZip(signed), archiveError("invalid_archive"));
  });
  it("validates empty deflated directory payloads", async () => {
    const zip = testZip([{ name: "empty/", data: Buffer.alloc(0) }]);
    await workspace(async (root) => {
      const result = await extractZip(zip, root);
      assert.deepEqual(await readdir(path.join(result.workingDirectory, "empty")), []);
    });
  });
  const unsafe = ["../escape", "/absolute", "C:/drive", "C:relative", "\\\\server\\share", "..\\escape",
    "a/../../escape", "a/./b", "a//b", "a/../b", "nul", "CON.txt", "a/COM1", "a:x", "a\0b",
    "a\nb", "trailing.", "trailing ", "a/<b", "e\u0301.txt"];
  for (const name of unsafe) {
    it(`rejects unsafe archive path ${JSON.stringify(name)} before creating a directory`, async () => {
      await workspace(async (root) => {
        await assert.rejects(extractZip(testZip([{ name }]), root), archiveError("unsafe_path"));
        assert.deepEqual(await readdir(root), []);
      });
    });
  }
  it("validates unsafe unselected entries too", async () => {
    await workspace(async (root) => {
      await assert.rejects(extractZip(testZip([{ name: "safe" }, { name: "../unsafe" }]), root, ["safe"]), archiveError("unsafe_path"));
      assert.deepEqual(await readdir(root), []);
    });
  });
  it("rejects ZIP symlinks and special entries", async () => {
    for (const name of ["symlink.zip", "fifo.zip"]) {
      const bytes = await fixture(name);
      assert.throws(() => listZip(bytes), archiveError("unsafe_entry"));
    }
    const reparse = testZip([{ name: "reparse" }]);
    const attributes = centralOffset(reparse) + 38;
    reparse.writeUInt32LE((reparse.readUInt32LE(attributes) | 0x400) >>> 0, attributes);
    assert.throws(() => listZip(reparse), archiveError("unsafe_entry"));
  });
  it("rejects alternate path/link-bearing extra fields and malformed extra lengths", () => {
    for (const id of [0x0001, 0x000d, 0x7075, 0x756e, 0x9901]) {
      const extra = Buffer.alloc(4); extra.writeUInt16LE(id, 0);
      assert.throws(() => listZip(testZip([{ name: "file", extra }])), archiveError("unsupported"));
    }
    assert.throws(() => listZip(testZip([{ name: "file", extra: Buffer.alloc(3) }])), archiveError("invalid_archive"));
    const timestamp = Buffer.from([0x55, 0x54, 1, 0, 0]);
    assert.equal(listZip(testZip([{ name: "file", extra: timestamp }])).length, 1);
  });
  it("rejects duplicate, case-alias and file/parent path collisions", () => {
    for (const names of [["a", "a"], ["A", "a"], ["a", "a/b"], ["a/b", "a"], ["a/x", "A/y"]]) {
      assert.throws(() => listZip(testZip(names.map((name) => ({ name })))), archiveError("unsafe_path"));
    }
  });
  it("rejects directory/file type disagreement", () => {
    assert.throws(() => listZip(testZip([{ name: "file", mode: 0o40700 }])), archiveError("unsafe_entry"));
    assert.throws(() => listZip(testZip([{ name: "directory/", data: Buffer.alloc(0), mode: 0o100600 }])), archiveError("unsafe_entry"));
  });
  it("bounds explicit and implicit entry counts and path depth", () => {
    assert.throws(() => listZip(testZip(Array.from({ length: 257 }, (_, i) => ({ name: `f${i}` })))), archiveError("limit_exceeded"));
    assert.throws(() => listZip(testZip(Array.from({ length: 129 }, (_, i) => ({ name: `d${i}/f` })))), archiveError("limit_exceeded"));
    assert.throws(() => listZip(testZip([{ name: Array.from({ length: 17 }, () => "d").join("/") } ])), archiveError("limit_exceeded"));
  });
  it("rejects compressed expansion-ratio bombs without inflating them", async () => {
    const bytes = await fixture("ratio-bomb.zip");
    assert.throws(() => listZip(bytes), archiveError("limit_exceeded"));
  });
  it("enforces per-entry and aggregate declared expansion ceilings", () => {
    assert.throws(() => listZip(testZip([{ name: "oversized", advertisedSize: ZIP_LIMITS.entryBytes + 1 }])), archiveError("limit_exceeded"));
    // Structurally valid metadata with opaque payloads: aggregate size must fail before any inflation.
    const rows = Array.from({ length: 3 }, (_, i) => ({ name: `part${i}`, advertisedSize: ZIP_LIMITS.entryBytes,
      compressed: Buffer.alloc(Math.ceil(ZIP_LIMITS.entryBytes / ZIP_LIMITS.compressionRatio)) }));
    assert.throws(() => listZip(testZip(rows)), archiveError("limit_exceeded"));
  });
  it("bounds actual inflation even when both headers lie about output size", async () => {
    const bytes = await fixture("ratio-bomb.zip");
    bytes.writeUInt32LE(8, 22);
    bytes.writeUInt32LE(8, centralOffset(bytes) + 24);
    assert.equal(listZip(bytes)[0]?.uncompressedBytes, 8);
    await workspace(async (root) => {
      await assert.rejects(extractZip(bytes, root), archiveError("limit_exceeded"));
      assert.deepEqual(await readdir(root), []);
    });
  });
  it("rejects trailing compressed data rather than ignoring a second stream", async () => {
    const data = Buffer.from("marker\n");
    const zip = testZip([{ name: "entry", data, compressed: Buffer.concat([deflateRawSync(data), Buffer.from("hidden")]) }]);
    await workspace(async (root) => {
      await assert.rejects(extractZip(zip, root), archiveError("integrity_error"));
      assert.deepEqual(await readdir(root), []);
    });
  });
  it("verifies payload CRC and removes partial extraction on failure", async () => {
    const bytes = testZip([{ name: "first" }, { name: "bad" }]);
    const cd = centralOffset(bytes);
    const secondCentral = cd + 46 + 5;
    const secondLocal = bytes.readUInt32LE(secondCentral + 42);
    const badCrc = bytes.readUInt32LE(secondCentral + 16) ^ 1;
    bytes.writeUInt32LE(badCrc >>> 0, secondCentral + 16);
    bytes.writeUInt32LE(badCrc >>> 0, secondLocal + 14);
    assert.equal(listZip(bytes).length, 2); // Listing is explicitly metadata-only.
    await workspace(async (root) => {
      await assert.rejects(extractZip(bytes, root), archiveError("integrity_error"));
      assert.deepEqual(await readdir(root), []);
      const selected = await extractZip(bytes, root, ["first"]); // Unselected payloads are not inflated.
      assert.equal(await readFile(path.join(selected.workingDirectory, "first"), "utf8"), "marker\n");
    });
  });
  it("rejects local/central path, size, compression and offset mismatches", async () => {
    const original = await fixture("single.zip");
    for (const offset of [30, 18, 8]) {
      const bytes = Buffer.from(original);
      bytes[offset] = bytes[offset]! ^ 1;
      assert.throws(() => listZip(bytes), ArchiveHelperError);
    }
    const bytes = Buffer.from(original);
    bytes.writeUInt32LE(1, centralOffset(bytes) + 42);
    assert.throws(() => listZip(bytes), archiveError("invalid_archive"));
  });
  it("rejects encrypted, unsupported-compression, split, ZIP64 and invalid archives", async () => {
    for (const flags of [1, 0x40, 0x2000]) assert.throws(() => listZip(testZip([{ name: "x", flags }])), archiveError("unsupported"));
    assert.throws(() => listZip(testZip([{ name: "x", method: 12 }])), archiveError("unsupported"));
    const original = await fixture("single.zip");
    const split = Buffer.from(original); split.writeUInt16LE(1, split.length - 18);
    assert.throws(() => listZip(split), archiveError("unsupported"));
    const zip64 = Buffer.from(original); zip64.writeUInt32LE(0xffffffff, zip64.length - 6);
    assert.throws(() => listZip(zip64), archiveError("unsupported"));
    for (const bytes of [Buffer.alloc(0), Buffer.from("not a zip"), original.subarray(0, -1), Buffer.concat([original, Buffer.from("trailer")])]) {
      assert.throws(() => listZip(bytes), archiveError("invalid_archive"));
    }
    assert.throws(() => listZip(Buffer.alloc(ZIP_LIMITS.archiveBytes + 1)), archiveError("limit_exceeded"));
  });
  it("accepts UTF-8 names and ZIP comments but rejects ambiguous legacy names", async () => {
    const zip = testZip([{ name: "résumé.txt" }]);
    const comment = Buffer.from("archive note");
    const commented = Buffer.concat([zip, comment]);
    commented.writeUInt16LE(comment.length, zip.length - 2);
    assert.equal(listZip(commented)[0]?.name, "résumé.txt");
    assert.throws(() => listZip(testZip([{ name: "résumé.txt", flags: 0 }])), archiveError("unsupported"));
    await workspace(async (root) => {
      const extracted = await extractZip(commented, root);
      assert.equal(await readFile(path.join(extracted.workingDirectory, "résumé.txt"), "utf8"), "marker\n");
    });
  });
  it("validates exact selections, supports an empty selection and keeps workspaces isolated", async () => {
    const bytes = await fixture("stored.zip");
    await workspace(async (root) => {
      await assert.rejects(extractZip(bytes, root, ["missing"]), archiveError("invalid_archive"));
      await assert.rejects(extractZip(bytes, root, ["binary.bin", "binary.bin"]), archiveError("unsafe_path"));
      await assert.rejects(extractZip(bytes, root, ["../bad"]), archiveError("unsafe_path"));
      assert.deepEqual(await readdir(root), []);
      const one = await extractZip(bytes, root, []);
      const two = await extractZip(bytes, root, []);
      assert.notEqual(one.workingDirectory, two.workingDirectory);
      assert.deepEqual(await readdir(one.workingDirectory), []);
      assert.deepEqual(one.entries, []);
    });
  });
  it("snapshots input bytes across asynchronous filesystem operations", async () => {
    const bytes = await fixture("single.zip");
    await workspace(async (root) => {
      const pending = extractZip(bytes, root);
      bytes.fill(0);
      const result = await pending;
      assert.equal(await readFile(path.join(result.workingDirectory, "plain.txt"), "utf8"), "marker\n");
    });
  });
  it("rejects symlink parents and symlink or hardlinked working files", async () => {
    await workspace(async (root) => {
      const real = path.join(root, "real"); await mkdir(real);
      const linked = path.join(root, "linked"); await symlink(real, linked);
      await assert.rejects(extractZip(await fixture("single.zip"), linked), archiveError("unsafe_path"));
      await assert.rejects(repackZip(linked), archiveError("unsafe_path"));
      await mkdir(path.join(real, "sub"));
      await assert.rejects(extractZip(await fixture("single.zip"), path.join(linked, "sub")), archiveError("unsafe_path"));
      const outside = path.join(root, "outside"); await writeFile(outside, "do not read");
      await symlink(outside, path.join(real, "link"));
      await assert.rejects(repackZip(real), archiveError("unsafe_entry"));
      await rm(path.join(real, "link"));
      await link(outside, path.join(real, "hardlink"));
      await assert.rejects(repackZip(real), archiveError("unsafe_entry"));
      assert.equal(await readFile(outside, "utf8"), "do not read");
    });
  });
  it("rejects relative working directory paths", async () => {
    await assert.rejects(extractZip(await fixture("single.zip"), "."), archiveError("unsafe_path"));
    await assert.rejects(repackZip("."), archiveError("unsafe_path"));
  });
  it("enforces repack size and count limits before reading oversized files", async () => {
    await workspace(async (root) => {
      const huge = path.join(root, "huge"); await writeFile(huge, ""); await truncate(huge, ZIP_LIMITS.entryBytes + 1);
      await assert.rejects(repackZip(root), archiveError("limit_exceeded"));
      await rm(huge);
      for (let i = 0; i < 257; i++) await writeFile(path.join(root, `f${i}`), "");
      await assert.rejects(repackZip(root), archiveError("limit_exceeded"));
    });
  });
  it("repackages an edited working directory into a deterministic ZIP and preserves untouched contents", async () => {
    await workspace(async (root) => {
      const source = await extractZip(await fixture("deflate.zip"), root);
      await writeFile(path.join(source.workingDirectory, "docs/README.md"), "# marker\nchanged\n");
      await writeFile(path.join(source.workingDirectory, "do-not-run.sh"), "exit 99\n", { mode: 0o755 });
      const packed = await repackZip(source.workingDirectory);
      assert.deepEqual(packed, await repackZip(source.workingDirectory));
      assert.ok(packed.length <= ZIP_LIMITS.archiveBytes);
      assert.ok(listZip(packed).every((entry) => entry.compression === "stored"));
      const result = await extractZip(packed, root);
      assert.equal(await readFile(path.join(result.workingDirectory, "docs/README.md"), "utf8"), "# marker\nchanged\n");
      assert.deepEqual(await readFile(path.join(result.workingDirectory, "binary.bin")), Buffer.from([0, 255, 7]));
      assert.deepEqual(await readdir(path.join(result.workingDirectory, "empty")), []);
      assert.equal((await lstat(path.join(result.workingDirectory, "do-not-run.sh"))).mode & 0o111, 0);
      assert.equal(await readFile(path.join(source.workingDirectory, "docs/README.md"), "utf8"), "# marker\nchanged\n");
    });
  });
  it("repacks and extracts an empty working directory", async () => {
    await workspace(async (root) => {
      const packed = await repackZip(root);
      assert.equal(packed.length, 22);
      assert.deepEqual(listZip(packed), []);
      const result = await extractZip(packed, root);
      assert.deepEqual(await readdir(result.workingDirectory), []);
    });
  });
  it("has a finite operation deadline", () => {
    const budget = new Budget();
    assert.ok(budget.remaining() > 0 && budget.remaining() <= ZIP_LIMITS.operationMs);
  });
});
