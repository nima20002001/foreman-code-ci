export async function copyProviderSchemas(directory: string,
  pinnedLauncher = require.resolve('@openai/codex/bin/codex.js')) {
  const lockfile = new URL('../../../../pnpm-lock.yaml', import.meta.url)
  const inputs = await Promise.all([readFile(pinnedLauncher), readFile(lockfile)])
  const manifest = JSON.parse(await readFile(join(dirname(pinnedLauncher), '../package.json'), 'utf8')) as { version: string }
  pinnedLauncher = await pinnedProviderExporter(manifest.version)
  const payload = await passiveDriverPayloads('codex', pinnedLauncher)
  if (!payload.complete || !payload.paths.length) throw new Error('Pinned provider schema exporter is unavailable.')
  const payloadHashes = await Promise.all(payload.paths.map(path => inventoryPayloadFingerprints.fingerprint(path)))
  const variants = ['stable', 'experimental']
  const cached = await cachedTestFixture(testFixtureCacheRoot(), 'codex-schemas',
    [...inputs, ...payloadHashes, pinnedLauncher, process.execPath,
      process.platform, process.arch, process.version, 'isolated-schema-export'], async temporary => {
      await mkdir(join(temporary, 'codex'), { mode: 0o700 })
      const environment = diagnosticEnvironment(temporary, {
        PATH: [dirname(process.execPath), '/usr/bin', '/bin'].join(delimiter),
      })
      const results = await Promise.allSettled(variants.map(async variant => {
        const args = [pinnedLauncher, 'app-server', 'generate-json-schema', '--out', join(temporary, variant)]
        if (variant === 'experimental') args.push('--experimental')
        await execute(process.execPath, args, { cwd: temporary, env: environment })
      }))
      const failures = results.flatMap(result => result.status === 'rejected' ? [result.reason] : [])
      if (failures.length) throw new AggregateError(failures, 'Provider schema generation failed.')
    })
  const copies = await Promise.allSettled(variants.map(async variant => {
    await mkdir(join(directory, variant), { recursive: true, mode: 0o700 })
    const filename = 'codex_app_server_protocol.schemas.json'
    await copyFile(join(cached, variant, filename), join(directory, variant, filename))
  }))
  const failures = copies.flatMap(result => result.status === 'rejected' ? [result.reason] : [])
  if (failures.length) throw new AggregateError(failures, 'Provider schema copy failed.')
}

/** The executable fixture emits schemas generated by the pinned installed CLI.
 * Every application qualification, manager and registry check remains native. */
export async function createRemoteReviewProvider(directory: string, launcher: string) {
  await mkdir(directory, { recursive: true, mode: 0o700 })
  const script = join(directory, 'provider.mjs')
  await copyFile(new URL('../fixtures/remote-review-codex.mjs', import.meta.url), script)
  const shell = join(directory, 'remote-review-shell.mjs')
  await copyFile(new URL('../fixtures/remote-review-shell.mjs', import.meta.url), shell)
  const source = join(directory, 'provider.c')
  const binary = join(directory, 'codex')
  const nodePath = JSON.stringify(process.execPath)
  const scriptPath = JSON.stringify(script)
  const rootPath = JSON.stringify(directory)
  await writeFile(source, `#include <unistd.h>
#include <stdlib.h>
int main(int argc, char **argv) {
  char **args = calloc((size_t)argc + 3, sizeof(char *));
  if (!args) return 127;
  setenv("REMOTE_REVIEW_CODEX_VERSION", "0.154.0", 1);
  args[0] = ${nodePath};
  args[1] = ${scriptPath};
  args[2] = ${rootPath};
  for (int i = 1; i < argc; ++i) args[i + 2] = argv[i];
  execv(args[0], args);
  return 127;
}
`, { mode: 0o600 })
  const preparation = await Promise.allSettled([
    measureIntegrationPhase('provider launcher', () => execute('cc', ['-O2', source, '-o', binary])),
    measureIntegrationPhase('provider schemas', () => copyProviderSchemas(directory)),
  ])
  const failures = preparation.flatMap(result => result.status === 'rejected' ? [result.reason] : [])
  if (failures.length) throw new AggregateError(failures, 'Provider fixture preparation failed.')
  const settings = join(directory, 'settings.json')
  const sandboxLauncher = require.resolve('@openai/codex/bin/codex.js')
  const sandboxPayload = await passiveDriverPayloads('codex', sandboxLauncher)
  if (!sandboxPayload.complete || !sandboxPayload.paths.length) throw new Error('Pinned native sandbox is unavailable.')
  const sandboxHome = join(directory, 'sandbox-home')
  await mkdir(sandboxHome, { mode: 0o700 })
  await writeFile(settings, JSON.stringify({ launcher,
    clientModule: require.resolve('@modelcontextprotocol/client'), sandboxLauncher, sandboxHome }), { mode: 0o600 })
  const payloadPaths = [script, shell, settings, process.execPath, sandboxLauncher, ...sandboxPayload.paths,
    join(directory, 'stable', 'codex_app_server_protocol.schemas.json'),
    join(directory, 'experimental', 'codex_app_server_protocol.schemas.json')]
  const originalBinary = await readFile(binary)
  const readActivity = async (filename: string): Promise<Array<Record<string, unknown>>> => {
    try {
      const contents = await readFile(join(directory, filename), 'utf8')
      return contents.split('\n').filter(Boolean).map(line => JSON.parse(line) as Record<string, unknown>)
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return []
      throw error
    }
  }
  return { directory, binary, payloadPaths,
    removePayload: () => rename(binary, join(directory, 'codex-unavailable')),
    async restorePayload() {
      const replacement = join(directory, 'codex-restored')
      await writeFile(replacement, originalBinary, { mode: 0o700 })
      await rename(replacement, binary)
    },
    async updatePayload() {
      const version = '0.156.1'
      const sourceText = await readFile(source, 'utf8')
      await writeFile(source, sourceText.replace('"0.154.0"', JSON.stringify(version)))
      const replacement = join(directory, 'codex-updated')
      await execute('cc', ['-O2', source, '-o', replacement])
      // Publish the payload and its version together so discovery sees one installation change.
      await rename(replacement, binary)
      return version
    },
    failModelRefresh: () => writeFile(join(directory, 'fail-model-refresh'), '', { mode: 0o600 }),
    hideModels: () => writeFile(join(directory, 'hide-models'), '', { mode: 0o600 }),
    showModels: () => rm(join(directory, 'hide-models')),
    blockModels: (options?: { workingDirectory: string }) => writeFile(join(directory, 'block-models'),
      options ? JSON.stringify(options) : '', { mode: 0o600 }),
    allowModelDirectories: async (directories: string[]) => {
      const destination = join(directory, 'allowed-model-directories')
      await writeFile(`${destination}.pending`, JSON.stringify(directories), { mode: 0o600 })
      await rename(`${destination}.pending`, destination)
    },
    releaseModels: async () => {
      await rm(join(directory, 'block-models'))
      await rm(join(directory, 'allowed-model-directories'), { force: true })
    },
    blockQualification: () => writeFile(join(directory, 'block-qualification'), '', { mode: 0o600 }),
    blockWorkflowAdmission: () => writeFile(join(directory, 'block-workflow-admission'), '', { mode: 0o600 }),
    releaseWorkflowAdmission: () => rm(join(directory, 'block-workflow-admission'), { force: true }),
    failWorkflowAdmission: () => writeFile(join(directory, 'fail-workflow-admission'), '', { mode: 0o600 }),
    releaseQualification: () => rm(join(directory, 'block-qualification')),
    blockVersions: () => writeFile(join(directory, 'block-versions'), '', { mode: 0o600 }),
    releaseVersions: () => rm(join(directory, 'block-versions')),
    invalidateVersions: () => writeFile(join(directory, 'invalid-versions'), '', { mode: 0o600 }),
    restoreVersions: () => rm(join(directory, 'invalid-versions')),
    calls: () => readActivity('calls.jsonl'),
    startupActivity: () => readActivity('startup.jsonl'),
    releaseReview: () => writeFile(join(directory, 'release-review'), '', { mode: 0o600 }),
    blockWorkflowTurns: (options?: { allowFirst: number }) => writeFile(join(directory, 'block-workflow-turns'),
      options ? JSON.stringify(options) : '', { mode: 0o600 }),
    releaseWorkflowTurns: () => rm(join(directory, 'block-workflow-turns'), { force: true }),
    retryReview: () => writeFile(join(directory, 'retry-review'), '', { mode: 0o600 }),
    blockRequesterSession: () => writeFile(join(directory, 'block-requester-session'), '', { mode: 0o600 }),
  }
}

export async function createRemoteReviewClaudeInventory(directory: string) {
  await mkdir(directory, { recursive: true, mode: 0o700 })
  const entrypoint = join(directory, 'sdk.mjs')
  const selectedExecutable = join(directory, 'claude')
  const installedLockPath = join(directory, 'pnpm-lock.yaml')
  await writeFile(entrypoint, 'export const inventoryRevision = 1\n', { mode: 0o600 })
  await writeFile(selectedExecutable, `#!/bin/sh
case "$1 $2 $3" in
  "--version  ") printf '2.1.5\\n' ;;
  "plugin list --json") printf '{"installed":[],"available":[]}\\n' ;;
  "plugin marketplace list") printf '[]\\n' ;;
  *) exit 1 ;;
esac
`, { mode: 0o700 })
  const bin = join(directory, '.local', 'bin')
  await mkdir(bin, { recursive: true, mode: 0o700 })
  await symlink(selectedExecutable, join(bin, 'claude'))
  await writeFile(join(directory, 'package.json'), JSON.stringify({
    name: '@anthropic-ai/claude-agent-sdk', version: '0.3.284',
  }), { mode: 0o600 })
  await writeFile(installedLockPath,
    'packages:\n  @anthropic-ai/claude-agent-sdk@0.3.284:\n    resolution: {integrity: sha512-Zml4dHVyZQ==}\n',
    { mode: 0o600 })
  return { sdk: { entrypoint, selectedExecutable, installedLockPath },
    updatePayload: () => writeFile(entrypoint, 'export const inventoryRevision = 2\n', { mode: 0o600 }) }
}

export async function createRemoteReviewTls(directory: string) {
  await mkdir(directory, { recursive: true, mode: 0o700 })
  const certificateFile = join(directory, 'certificate.pem')
  const privateKeyFile = join(directory, 'private-key.pem')
  await execute('openssl', ['req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-days', '2',
    '-subj', '/CN=localhost', '-addext', 'subjectAltName=DNS:localhost,IP:127.0.0.1',
    '-addext', 'basicConstraints=critical,CA:TRUE', '-keyout', privateKeyFile, '-out', certificateFile])
  await chmod(certificateFile, 0o600)
  await chmod(privateKeyFile, 0o600)
  return { certificateFile, privateKeyFile, trustCertificateFile: certificateFile }
}

/** Build the same committed artifact used by the installer. An
 * unsupported host fails the real packaging gate instead of substituting facts. */
export async function buildRemoteReviewWorkerRelease(directory: string) {
  return measureIntegrationPhase('Worker artifact', () => cachedWorkerRelease(directory))
}

async function cachedWorkerRelease(directory: string) {
  const suppliedRelease = readProductEnvironment(process.env, 'TEST_WORKER_RELEASE')
  if (suppliedRelease) return suppliedRelease
  const { hostFacts } = await import(new URL('../../../worker/src/diagnostics.mjs', import.meta.url).href)
  const facts = await hostFacts(homedir(), [directory]) as {
    os: string; osRelease: string; arch: string; libc: string; node: string
  }
  const targets = [
    'test-hosts/ubuntu-24.04-x64-target.json', 'ubuntu-26.04-x64-target.json',
    'test-hosts/ubuntu-24.04-x64-node-22.23.2-target.json', 'test-hosts/ubuntu-26.04-x64-node-22.23.2-target.json',
  ]
  for (const name of targets) {
    const targetFile = fileURLToPath(new URL(`../../../worker/artifacts/${name}`, import.meta.url))
    const targetBytes = await readFile(targetFile)
    const target = JSON.parse(targetBytes.toString('utf8')) as typeof facts
    const fields = ['os', 'osRelease', 'arch', 'libc', 'node'] as const
    if (!fields.every(field => target[field] === facts[field])) continue
    const root = fileURLToPath(new URL('../../../..', import.meta.url))
    const requestedCommit = readProductEnvironment(process.env, 'WORKER_BUILD_COMMIT')
    if (requestedCommit && !/^[a-f0-9]{40}$/.test(requestedCommit)) throw new Error('Invalid captured commit')
    const commit = (await execute('git', ['rev-parse', requestedCommit ?? 'HEAD'], { cwd: root })).stdout.trim()
    // Cache hits retain the builder's committed-control-input gate.
    await execute('git', ['diff', '--quiet', commit, '--',
      'scripts/build-worker-artifact.mjs', 'scripts/worker-artifact-files.mjs',
      'scripts/quota-helper-abi.mjs', 'packages/contracts/package.json', 'packages/contracts/src/productEnvironment.mjs',
      'apps/worker/package.json', 'package.json', 'pnpm-workspace.yaml', 'pnpm-lock.yaml', targetFile], { cwd: root })
    const builder = fileURLToPath(new URL('../../../../scripts/build-worker-artifact.mjs', import.meta.url))
    const cached = await cachedWorkerReleaseEntry(testFixtureCacheRoot(), root, commit,
      [targetBytes, process.platform, process.arch, process.version], async temporary => {
        await execute(process.execPath, [builder, targetFile, join(temporary, 'release')], {
          maxBuffer: 4 * 1024 * 1024,
          env: { ...process.env, FOREMAN_CODE_WORKER_BUILD_COMMIT: commit },
        })
      })
    return join(cached, 'release')
  }
  throw new Error(`No approved Worker packaging target matches ${JSON.stringify(facts)}.`)
}
